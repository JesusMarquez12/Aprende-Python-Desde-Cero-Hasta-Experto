# String method replace

string = "Hello, World!"
print(f'Original string: {string}')

# Example of replace method
new_string = string.replace('World', 'to all.')
print(f'New replaced string: {new_string}')

# Replace hello text with bye
new_string = string.replace('Hello', 'Bye')
print(f'New replaced string: {new_string}')