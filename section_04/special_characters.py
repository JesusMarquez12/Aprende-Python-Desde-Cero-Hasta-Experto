# Essential Special characters
print('Hello\nWorld')            # \n new line
print('\t\tPython \t\tis great') # \t add a tabulation
print('Juan\' Perez')            # \' add a simple quotation mark in a simple quotation mark delimited string
print("Karla\" Gomez")           # \" add a double quotation mark in a double quotation mark delimited string
print('Character \\ Perez')      # \\ add a inverted slash without mark a special character