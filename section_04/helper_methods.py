# String helper methods

string_1 = 'Hello World.'
print(f'Original string: {string_1}')

# Turn to uppercase
upper = string_1.upper()
print(f'Uppercase string: {upper}')

# Turn to lowercase
print(f'Lowercase string: {string_1.lower()}')

string_2 = ' Juan Perez '
# Remove leading and trailing whitespaces
print(f'String with whitespaces\t\t: {string_2}')
print(f'String without whitespaces\t: {string_2.strip()}')

