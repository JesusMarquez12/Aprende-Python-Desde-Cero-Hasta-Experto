# Operators are special symbols that execute specific actions:
# Arithmetic Operators:  Allow execute mathematical tasks, such as addition,
# multiplication and others
# Assignation Operators: Allow to assign values to variables
# Comparison Operators: Used to compare values from one variable to another
# Logic operators: Used to combine conditional or logical expressions
# Identity Operators: To verify if two variables are the same object
# Membership Operators: To check if a sequence is present in an object.