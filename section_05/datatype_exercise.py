# Example datatypes

# Concatenation or values sum example
string_number_1 = "10"
print(f"String number 1: {string_number_1}")

string_number_2 = "20"
print(f"String number 2: {string_number_2}")

result = string_number_1 + string_number_2
print(f"Concatenation: {result}")

# Integer conversion
int_number_1 = int(string_number_1)
int_number_2 = int(string_number_2)
result = int_number_1 + int_number_2
print(f"Sum of integers: {result}")